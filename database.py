def get_conn(url):
    """Conexión a PostgreSQL a partir de la URL de Supabase.

    autocommit: cada consulta suelta se confirma sola y las lecturas no dejan
    transacciones abiertas; las escrituras de varios pasos usan
    `conn.transaction()`. prepare_threshold=None porque el pooler de Supabase
    en modo transacción no admite sentencias preparadas.
    """
    return psycopg.connect(
        url, autocommit=True, row_factory=dict_row, prepare_threshold=None
    )


def conexion_viva(conn):
    """True si la conexión sigue respondiendo. Supabase corta las conexiones
    inactivas, y la app deja la suya abierta entre visitas."""
    if conn.closed:
        return False
    try:
        conn.execute("SELECT 1")
        return True
    except psycopg.Error:
        return False


def init_db(conn):
    with conn.transaction():
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS clientes (
                id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre              TEXT NOT NULL,
                empresa             TEXT,
                telefono            TEXT,
                email               TEXT,
                ubicacion           TEXT,
                giro_negocio        TEXT,
                productos_interes   TEXT,
                estado              TEXT NOT NULL DEFAULT 'Negociación',
                tipo                TEXT NOT NULL DEFAULT 'Cliente',
                fecha_creacion      TEXT NOT NULL,
                proximo_seguimiento TEXT
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS contactos (
                id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                cliente_id    INTEGER NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
                fecha         TEXT NOT NULL,
                tipo_contacto TEXT NOT NULL,
                notas         TEXT,
                resultado     TEXT
            )
            """
        )
        conn.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_contactos_cliente
                ON contactos (cliente_id, fecha DESC)
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS usuarios (
                id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario         TEXT NOT NULL,
                nombre          TEXT NOT NULL,
                contrasena_hash TEXT NOT NULL,
                rol             TEXT NOT NULL DEFAULT 'Usuario',
                activo          INTEGER NOT NULL DEFAULT 1,
                fecha_creacion  TEXT NOT NULL,
                ultimo_acceso   TEXT
            )
            """
        )
        # Nombre de usuario único sin distinguir mayúsculas.
        conn.execute(
            """
            CREATE UNIQUE INDEX IF NOT EXISTS idx_usuarios_usuario
                ON usuarios (LOWER(usuario))
            """
        )

        # Registro de actividad. Guarda el nombre del usuario y del registro
        # como texto, sin claves foráneas, para que la historia siga legible
        # aunque después se eliminen.
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS actividad (
                id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                fecha          TEXT NOT NULL,
                usuario_id     INTEGER,
                usuario_nombre TEXT NOT NULL,
                accion         TEXT NOT NULL,
                detalle        TEXT
            )
            """
        )
        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_actividad_fecha ON actividad (fecha DESC)"
        )

        # Usuarios responsables de cada registro (pueden ser varios). Al
        # eliminar el usuario o el registro, la asignación desaparece sola.
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS asignaciones (
                cliente_id INTEGER NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
                usuario_id INTEGER NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
                PRIMARY KEY (cliente_id, usuario_id)
            )
            """
        )
        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_asignaciones_usuario ON asignaciones (usuario_id)"
        )
        # Antes cada registro tenía un solo usuario en `asignado_a`: se pasa a
        # la tabla nueva y se quita la columna para que no quede desfasada.
        if conn.execute(
            """
            SELECT 1 FROM information_schema.columns
             WHERE table_name = 'clientes' AND column_name = 'asignado_a'
            """
        ).fetchone():
            conn.execute(
                """
                INSERT INTO asignaciones (cliente_id, usuario_id)
                SELECT id, asignado_a FROM clientes WHERE asignado_a IS NOT NULL
                ON CONFLICT DO NOTHING
                """
            )
            conn.execute("ALTER TABLE clientes DROP COLUMN asignado_a")

        # Suplidor que atiende a cada cliente (opcional). Si se elimina el
        # suplidor, sus clientes quedan sin suplidor.
        conn.execute(
            """
            ALTER TABLE clientes ADD COLUMN IF NOT EXISTS suplidor_id INTEGER
                REFERENCES clientes (id) ON DELETE SET NULL
            """
        )

        # La cédula (o RNC) aparece en la factura.
        conn.execute("ALTER TABLE clientes ADD COLUMN IF NOT EXISTS cedula TEXT")

        # `datos` guarda en JSON todo lo que lleva la factura (cliente,
        # personas, líneas...) tal como se emitió, y `pdf` el archivo: aunque
        # después cambie la ficha del cliente, la factura se descarga igual.
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS facturas (
                id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                numero         TEXT NOT NULL UNIQUE,
                anio           INTEGER NOT NULL,
                secuencia      INTEGER NOT NULL,
                cliente_id     INTEGER REFERENCES clientes (id) ON DELETE SET NULL,
                cliente_nombre TEXT NOT NULL,
                fecha_emision  TEXT NOT NULL,
                total          DOUBLE PRECISION NOT NULL,
                datos          TEXT NOT NULL,
                pdf            BYTEA NOT NULL,
                creado_por     TEXT,
                fecha_creacion TEXT NOT NULL,
                UNIQUE (anio, secuencia)
            )
            """
        )
        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_facturas_cliente ON facturas (cliente_id, id DESC)"
        )

        # Ajustes que cambia un administrador (p. ej. el próximo número de
        # factura fijado a mano).
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS configuracion (
                clave TEXT PRIMARY KEY,
                valor TEXT NOT NULL
            )
            """
        )

        # El seguimiento ya no se fija a mano: los registros que quedaron sin
        # fecha reciben la calculada.
        for row in conn.execute(
            "SELECT id FROM clientes WHERE proximo_seguimiento IS NULL OR proximo_seguimiento = ''"
        ).fetchall():
            recalcular_seguimiento(conn, row["id"])


