def get_conn(url):
    """Conexión a PostgreSQL a partir de la URL de Supabase.

    autocommit: cada consulta suelta se confirma sola y las lecturas no dejan
    transacciones abiertas; las escrituras de varios pasos usan
    `conn.transaction()`. prepare_threshold=None porque el pooler de Supabase
    en modo transacción no admite sentencias preparadas.
    """
    return psycopg.connect(
        url, autocommit=True, row_factory=dict_row, prepare_threshold=None
    )


def conexion_viva(conn):
    """True si la conexión sigue respondiendo. Supabase corta las conexiones
    inactivas, y la app deja la suya abierta entre visitas."""
    if conn.closed:
        return False
    try:
        conn.execute("SELECT 1")
        return True
    except psycopg.Error:
        return False


def init_db(conn):
    with conn.transaction():
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS clientes (
                id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre              TEXT NOT NULL,
                empresa             TEXT,
                telefono            TEXT,
                email               TEXT,
                ubicacion           TEXT,
                giro_negocio        TEXT,
                productos_interes   TEXT,
                estado              TEXT NOT NULL DEFAULT 'Negociación',
                tipo                TEXT NOT NULL DEFAULT 'Cliente',
                fecha_creacion      TEXT NOT NULL,
                proximo_seguimiento TEXT
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS contactos (
                id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                cliente_id    INTEGER NOT NULL REFERENCES clientes (id) ON DELETE CASCADE,
                fecha         TEXT NOT NULL,
                tipo_contacto TEXT NOT NULL,
                notas         TEXT,
                resultado     TEXT
            )
            """
        )
        conn.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_contactos_cliente
                ON contactos (cliente_id, fecha DESC)
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS usuarios (
                id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario         TEXT NOT NULL,
                nombre          TEXT NOT NULL,
                contrasena_hash TEXT NOT NULL,
                rol             TEXT NOT NULL DEFAULT 'Usuario',
                activo          INTEGER NOT NULL DEFAULT 1,
                fecha_creacion  TEXT NOT NULL,
                ultimo_acceso   TEXT
            )
            """
        )
        # Nombre de usuario único sin distinguir mayúsculas.
        conn.execute(
            """
            CREATE UNIQUE INDEX IF NOT EXISTS idx_usuarios_usuario
                ON usuarios (LOWER(usuario))
            """
        )

        # El seguimiento ya no se fija a mano: los registros que quedaron sin
        # fecha reciben la calculada.
        for row in conn.execute(
            "SELECT id FROM clientes WHERE proximo_seguimiento IS NULL OR proximo_seguimiento = ''"
        ).fetchall():
            recalcular_seguimiento(conn, row["id"])


