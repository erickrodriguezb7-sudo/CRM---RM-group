def listar_clientes(conn, busqueda="", estado="Todos", tipo="Ambos"):
    """Lista suplidores y clientes con su último contacto y total de contactos.

    La búsqueda cubre nombre, empresa, ubicación y productos de interés, sin
    distinguir mayúsculas. `tipo` filtra por "Cliente" o "Suplidor"; "Ambos"
    no filtra.
    """
    sql = """
        SELECT c.*,
               MAX(ct.fecha)                     AS ultimo_contacto,
               COUNT(ct.id)                      AS total_contactos
          FROM clientes c
          LEFT JOIN contactos ct ON ct.cliente_id = c.id
         WHERE 1 = 1
    """
    params = {}

    if busqueda:
        sql += """
             AND (c.nombre ILIKE %(q)s OR c.empresa ILIKE %(q)s
                  OR c.ubicacion ILIKE %(q)s OR c.productos_interes ILIKE %(q)s)
        """
        params["q"] = f"%{busqueda}%"

    if estado and estado != "Todos":
        sql += " AND c.estado = %(estado)s"
        params["estado"] = estado

    if tipo and tipo != "Ambos":
        sql += " AND c.tipo = %(tipo)s"
        params["tipo"] = tipo

    sql += " GROUP BY c.id ORDER BY LOWER(c.nombre)"
    return conn.execute(sql, params).fetchall()


