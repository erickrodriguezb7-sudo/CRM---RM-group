def ahora():
    return datetime.now(ZONA_HORARIA)


def registrar_actividad(conn, usuario, accion, detalle=""):
    """Anota quién hizo qué. `usuario` es el dict del usuario con sesión."""
    conn.execute(
        """
        INSERT INTO actividad (fecha, usuario_id, usuario_nombre, accion, detalle)
        VALUES (%s, %s, %s, %s, %s)
        """,
        (
            ahora().strftime("%Y-%m-%d %H:%M:%S"),
            usuario["id"],
            f"{usuario['nombre']} ({usuario['usuario']})",
            accion,
            detalle,
        ),
    )


def listar_actividad(conn, desde, hasta, usuario_id=None, accion=None, limite=2000):
    """Actividad entre dos fechas (ambas incluidas), de la más reciente a la
    más antigua."""
    sql = """
        SELECT fecha, usuario_nombre, accion, detalle
          FROM actividad
         WHERE fecha >= %(desde)s AND fecha < %(hasta)s
    """
    params = {
        "desde": desde.isoformat(),
        "hasta": (hasta + timedelta(days=1)).isoformat(),
        "limite": limite,
    }
    if usuario_id is not None:
        sql += " AND usuario_id = %(usuario_id)s"
        params["usuario_id"] = usuario_id
    if accion:
        sql += " AND accion = %(accion)s"
        params["accion"] = accion
    sql += " ORDER BY fecha DESC, id DESC LIMIT %(limite)s"
    return conn.execute(sql, params).fetchall()


def acciones_registradas(conn):
    return [
        r["accion"]
        for r in conn.execute("SELECT DISTINCT accion FROM actividad ORDER BY accion")
    ]
